import assert from 'node:assert/strict';
import { labelsFor, planTiming, defaults } from './timing_planner.mjs';
const old={sourceFrames:[0,1,2],candidates:[0,2],labels:['X','C'],jumps:{}};
assert.deepEqual(labelsFor(old),['X','X','C']);
assert.deepEqual(labelsFor({...old,mouthStates:['closed','open','uncertain']}),['X','?','C']);
assert.deepEqual(labelsFor({...old,mouthStates:['closed','uncertain','closed']}),['X','X','X']);
assert.throws(()=>labelsFor({...old,mouthStates:['invalid']}));
const bank={sourceFrames:[0,1,2,3],candidates:[0,1,2,3],labels:['X','X','X','X'],mouthStates:['closed','open','open','closed'],jumps:{}};
const timing={duration:.5,inserted_pauses:[],quiet_candidates:[],envelope:[1],quiet_threshold:.1};
const plan=planTiming([{start:0,end:.5,value:'B'}],timing,bank,{first:0,end:4},defaults.en);
const checked={...bank,reviewedLoop:{first:0,end:4,face:.01,velocity:.005,maxFace:.02,maxVelocity:.01}};
assert.doesNotThrow(()=>planTiming([{start:0,end:.5,value:'B'}],timing,checked,{first:0,end:4},defaults.en));
assert.throws(()=>planTiming([{start:0,end:.5,value:'B'}],timing,{...checked,reviewedLoop:{...checked.reviewedLoop,face:.03}},{first:0,end:4},defaults.en));
assert.throws(()=>planTiming([{start:0,end:.5,value:'B'}],timing,checked,{first:0,end:3},defaults.en));
for(let i=0;i<plan.frames.length;i++)assert.ok(Number.isFinite(plan.sourceSecondsAt(i/24)));
console.log('Visual policy: legacy unchanged, reviewed closure override, unknown fine shape, invalid state, bounded clock: OK');
