"""Freeze reviewed inference code and trained RF weights; no training at build time."""
import ast
import base64
import hashlib
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'experiments/isa_classifier'
TARGET=ROOT/'api/services/isa_ml'
FUNCTIONS={
 'classifier':{'audio_features','labels_at','timeline'},
 'temporal':set(),
 'boosted_classifier':{'tree_context','decode'},
 'forest_classifier':{'load_forest','probabilities_from_arrays','predict'},
 'rhythm_features':{'_ages','timing_features'},
 'phonetic_features':{'hybrid_features'},
 'phoneme_identity':{'identity_features'},
 'phonetic_alignment':{'expand_diphthongs','grouped_durations','phone_shapes','append_cue'},
}

def main():
 TARGET.mkdir(parents=True,exist_ok=True)
 (TARGET/'__init__.py').write_text('"""Frozen Isa RF V2 inference, independent of experiments and sklearn."""\n')
 sources={}
 for name,functions in FUNCTIONS.items():
  raw=(SOURCE/f'{name}.py').read_text(encoding='utf8');tree=ast.parse(raw)
  tree.body=[n for n in tree.body if not isinstance(n,(ast.FunctionDef,ast.AsyncFunctionDef)) or n.name in functions]
  for n in ast.walk(tree):
   if isinstance(n,ast.ImportFrom) and n.module in FUNCTIONS:n.level=1
  (TARGET/f'{name}.py').write_text('# Frozen inference subset; generated by scripts/package_isa_forest.py.\n'+ast.unparse(tree)+'\n',encoding='utf8')
  sources[name]=hashlib.sha256(raw.encode()).hexdigest()
 weights=TARGET/'weights';weights.mkdir(exist_ok=True)
 hashes={}
 for language in ('es','en'):
  model=json.loads((ROOT/f'tmp/isa-own-classifier/forest-review-v2/hybrid-{language}.json').read_text())
  data=base64.b64decode(model.pop('forest_npz'),validate=True)
  model.pop('training',None)
  (weights/f'{language}.npz').write_bytes(data)
  (weights/f'{language}.json').write_text(json.dumps(model,separators=(',',':')),encoding='utf8')
  hashes[language]=hashlib.sha256(data).hexdigest()
 (weights/'provenance.json').write_text(json.dumps({'release':'isa-rf-v2','weights_sha256':hashes,'source_sha256':sources},indent=2))
 print(json.dumps({'release':'isa-rf-v2','weights_sha256':hashes}))

if __name__=='__main__':main()
